import { test, expect } from '@playwright/test';
import { fixtures, mint, wallet } from './support';
test.beforeEach(async ({ page }) => { await fixtures(page); await page.goto('/popup.html?view=sidepanel'); });
test('manual social evidence, safe notes and import/export', async ({ page }) => {
  const social = page.getByRole('region', { name: 'Manual social analysis' });
  await social.getByRole('textbox', { name: 'Public social text' }).fill(`X post says CA ${mint}. A claim is not evidence.`);
  await social.getByRole('button', { name: 'Analyze pasted text' }).click();
  await expect(social.getByText(/Source-confirmed Solana market/)).toBeVisible();
  await social.getByRole('textbox', { name: 'Public social text' }).fill(wallet);
  await social.getByRole('button', { name: 'Analyze pasted text' }).click();
  await expect(social.getByText(/Address candidate · No indexed Solana pool/)).toBeVisible();
  await social.getByRole('textbox', { name: 'Social link URL' }).fill('https://user:password@x.com/post');
  await social.getByRole('button', { name: 'Save note', exact: true }).click();
  await expect(social.getByText('Use a public HTTPS URL without credentials.')).toBeVisible();
  await social.getByRole('textbox', { name: 'Social link URL' }).fill('https://t.me/public/42');
  await social.getByRole('textbox', { name: 'Social note', exact: true }).fill('My manual social note');
  await social.getByRole('button', { name: 'Save note', exact: true }).click();
  await expect(social.getByText('My manual social note', { exact: true })).toBeVisible();
  const download = page.waitForEvent('download'); await social.getByRole('button', { name: 'Export notes' }).click();
  expect((await download).suggestedFilename()).toBe('tail-social-notes.json');
  await social.getByLabel('Import social notes').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ version: 1, notes: [{ id: 'bad', mint: 'invalid' }] })) });
  await expect(social.getByText(/Invalid social notes export/)).toBeVisible();
  await social.getByLabel('Import social notes').setInputFiles({ name: 'valid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ version: 1, notes: [{ id: 'imported', mint, url: 'https://x.com/public/12', note: 'Imported user-provided note', at: Date.now() }] })) });
  await expect(social.getByText('Imported user-provided note', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('My manual social note', { exact: true })).toBeVisible();
});
test('social input stays manual and provider failures remain unavailable', async ({ page }) => {
  let socialFetches = 0;
  await page.route(/https:\/\/(x.com|t.me)\//, route => { socialFetches++; return route.abort(); });
  const social = page.getByRole('region', { name: 'Manual social analysis' });
  await social.getByRole('textbox', { name: 'Public social text' }).fill('https://x.com/public/1 invalid 0xdeadbeef');
  await social.getByRole('button', { name: 'Analyze pasted text' }).click();
  await expect(social.getByText('No valid 32-byte Solana address candidates in this text.')).toBeVisible();
  expect(socialFetches).toBe(0);
  await page.route('**/dex/**', route => route.fulfill({ status: 429, json: { error: 'Source fixture rate limit' } }));
  await social.getByRole('textbox', { name: 'Public social text' }).fill(mint);
  await social.getByRole('button', { name: 'Analyze pasted text' }).click();
  await expect(social.getByText(/Address candidate/)).toContainText(/429|unavailable|rate/i);
  await expect(social.getByRole('button', { name: 'Open token in TAIL' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Scan active page now' }).click();
  await expect(page.getByText('Page scanning requires the installed Chrome extension. Paste text below.')).toBeVisible();
});
