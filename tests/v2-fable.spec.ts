import { test, expect } from '@playwright/test';
import { fixtures, mint, errors } from './support';
test('unconfigured Fable exposes factual local tools without pretending to be a model', async ({ page }) => {
  await fixtures(page); let modelCalls = 0;
  await page.route('**/api/astra/chat', route => { modelCalls++; return route.fulfill({ status: 503, json: { error: 'Not configured fixture' } }); });
  await page.route('https://fonts.googleapis.com/**', r => r.fulfill({ contentType: 'text/css', body: '' }));
  await page.goto('/terminal'); await expect(page.locator('.tail-terminal-route:not([inert])')).toBeVisible();
  const panel = page.locator('.fable-panel');
  await expect(panel.getByText('Currently unavailable', { exact: true })).toBeVisible();
  await expect(panel.getByRole('textbox', { name: 'Ask Fable 5.2', exact: true })).toBeEditable();
  await panel.getByText('Local data tools · no AI required', { exact: true }).click();
  await panel.getByLabel('Local data tool', { exact: true }).selectOption('explain_chart_indicator');
  await panel.getByRole('button', { name: 'Run local data tool', exact: true }).click();
  await expect(panel.getByText('Factual tool output · no AI response', { exact: true })).toBeVisible();
  await expect(panel.locator('[aria-label="Factual local tool result"] pre')).toContainText('Wilder smoothing');
  await panel.getByLabel('Local data tool', { exact: true }).selectOption('get_market_data');
  await panel.getByLabel('Local tool arguments', { exact: true }).fill(JSON.stringify({ mint }));
  await panel.getByRole('button', { name: 'Run local data tool', exact: true }).click();
  await expect(panel.locator('[aria-label="Factual local tool result"] pre')).toContainText('DexScreener');
  await expect(panel.locator('[aria-label="Factual local tool result"] pre')).toContainText('"mintAuthority"');
  await expect(panel.locator('[aria-label="Factual local tool result"] pre')).toContainText('"unavailable"');
  expect(modelCalls).toBe(0);
  const composer = panel.getByRole('textbox', { name: 'Ask Fable 5.2', exact: true });
  const draft = 'Keep this question while the service is unavailable.';
  await composer.fill(draft);
  await panel.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('Your draft is still here.');
  await expect(composer).toHaveValue(draft);
  await expect(panel.locator('.fable-transcript > article')).toHaveCount(0);
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('tail.fable.history.v1') ?? '[]'))).toEqual([]);
  expect(modelCalls).toBe(1); expect(errors.get(page)).toEqual([]);
});
test('workspace proposals wait for visible review and never apply themselves', async ({ page }) => {
  await fixtures(page); await page.goto('/terminal'); await expect(page.locator('.tail-terminal-route:not([inert])')).toBeVisible();
  await page.evaluate(() => { (window as any).fableProposals = []; window.addEventListener('tail:workspace-proposal', e => (window as any).fableProposals.push((e as CustomEvent).detail)); });
  const panel = page.locator('.fable-panel');
  await panel.getByText('Local data tools · no AI required', { exact: true }).click();
  await panel.getByLabel('Local data tool', { exact: true }).selectOption('configure_workspace');
  await panel.getByRole('button', { name: 'Run local data tool', exact: true }).click();
  await expect(panel.getByText('These changes have not been applied.', { exact: false })).toBeVisible();
  expect(await page.evaluate(() => (window as any).fableProposals)).toEqual([]);
  const workspaceBefore = await page.evaluate(() => localStorage.getItem('tail.workspace.v1'));
  await panel.getByRole('button', { name: 'Review proposal 1', exact: true }).click();
  expect(await page.evaluate(() => (window as any).fableProposals)).toEqual([{ type: 'open_widget', widget: 'compare' }]);
  const confirmation = page.getByRole('dialog', { name: 'Review workspace action', exact: true });
  await expect(confirmation).toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem('tail.workspace.v1'))).toBe(workspaceBefore);
  await confirmation.getByRole('button', { name: 'Cancel workspace action', exact: true }).click();
  await expect(confirmation).toHaveCount(0);
  expect(await page.evaluate(() => localStorage.getItem('tail.workspace.v1'))).toBe(workspaceBefore);
  await panel.getByLabel('Local tool arguments', { exact: true }).fill(JSON.stringify({ actions: [{ type: 'send_transaction' }] }));
  await panel.getByRole('button', { name: 'Run local data tool', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('workspace proposal');
  expect(await page.evaluate(() => (window as any).fableProposals)).toHaveLength(1);
});
test('standalone chat passes bounded context and renders source-backed fixture usage and proposals', async ({ page }) => {
  await fixtures(page); let request: any;
  await page.route('**/api/astra/status', route => route.fulfill({ json: { configured: true, ready: true, model: 'fixture-provider', rateLimit: 'local' } }));
  await page.route('**/api/astra/chat', route => { request = route.request().postDataJSON(); return route.fulfill({ json: { text: 'Fixture model output from the mocked existing API.', model: 'fixture-provider', at: Date.now(), sources: [], proposals: [{ type: 'open_widget', widget: 'data' }], usage: { requests: 1, inputTokens: 100, outputTokens: 20, totalTokens: 120, estimatedCostUsd: null, pricingSource: null } } }); });
  await page.goto('/terminal'); await expect(page.locator('.tail-terminal-route:not([inert])')).toBeVisible();
  await expect(page.locator('.fable-panel .fable-heading p')).toHaveText('Ready');
  await page.evaluate(() => window.dispatchEvent(new CustomEvent('tail:workspace-context', { detail: { mint: null, interval: '5m', chartMode: 'line', filters: null, widgets: ['chart', 'compare'], allowPortfolio: false } })));
  const panel = page.locator('.fable-panel');
  await expect(panel.locator('.fable-transcript')).toContainText('interval: 5m');
  await panel.getByRole('textbox', { name: 'Ask Fable 5.2', exact: true }).fill('Show evidence and propose diagnostics');
  await expect(panel.getByRole('textbox', { name: 'Ask Fable 5.2', exact: true })).toHaveValue('Show evidence and propose diagnostics');
  await panel.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(panel.getByText('Fixture model output from the mocked existing API.', { exact: true })).toBeVisible();
  await expect(panel.getByText('Provider requests: 1', { exact: false })).toBeVisible();
  await expect(panel.getByText('pricing or provider usage not supplied', { exact: false })).toBeVisible();
  await expect(panel.getByRole('button', { name: 'Review proposal 1', exact: true })).toBeVisible();
  expect(request.workspaceContext).toMatchObject({ interval: '5m', chartMode: 'line', allowPortfolio: false, widgets: ['chart', 'compare'] });
  expect(request).not.toHaveProperty('portfolio'); expect(request).not.toHaveProperty('apiKey');
  expect(errors.get(page)).toEqual([]);
});
